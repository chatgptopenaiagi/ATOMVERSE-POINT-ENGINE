-- Run only against the dedicated ATOMVERSE_POINT_ENGINE database.
-- Additive, repeatable schema migration. No modification of existing applications.
IF OBJECT_ID('SCHEMA_MIGRATIONS') IS NULL
CREATE TABLE SCHEMA_MIGRATIONS(version int PRIMARY KEY, applied_utc datetime2(7) NOT NULL DEFAULT SYSUTCDATETIME());
IF OBJECT_ID('POINT_ENTITIES') IS NULL
CREATE TABLE POINT_ENTITIES(point_id varchar(36) PRIMARY KEY);
IF OBJECT_ID('POINT_SESSIONS') IS NULL
CREATE TABLE POINT_SESSIONS(session_id varchar(36) PRIMARY KEY,point_id varchar(36) NOT NULL REFERENCES POINT_ENTITIES(point_id),created_ns bigint NOT NULL,config nvarchar(max) NOT NULL);
IF OBJECT_ID('POINT_EVENTS') IS NULL
BEGIN
CREATE TABLE POINT_EVENTS(
 session_id varchar(36) NOT NULL REFERENCES POINT_SESSIONS(session_id),seq bigint NOT NULL,
 kind varchar(32) NOT NULL,tick bigint NOT NULL,sim_time float NOT NULL,
 utc_ns bigint NOT NULL,monotonic_ns bigint NOT NULL,utc_time datetime2(7) NOT NULL,
 x float NULL,y float NULL,z float NULL,payload nvarchar(max) NOT NULL,
 CONSTRAINT PK_POINT_EVENTS PRIMARY KEY CLUSTERED(session_id,seq));
CREATE INDEX IX_POINT_REPLAY ON POINT_EVENTS(session_id,kind,tick) INCLUDE(sim_time,x,y,z);
END;
IF NOT EXISTS(SELECT 1 FROM SCHEMA_MIGRATIONS WHERE version=1) INSERT INTO SCHEMA_MIGRATIONS(version) VALUES(1);
GO
CREATE OR ALTER VIEW POINT_STATE_SAMPLES AS SELECT * FROM POINT_EVENTS WHERE kind='sample';
GO
CREATE OR ALTER VIEW POINT_COMMANDS AS SELECT * FROM POINT_EVENTS WHERE kind IN ('command','projection');
GO
CREATE OR ALTER VIEW POINT_TRAJECTORIES AS SELECT * FROM POINT_EVENTS WHERE kind='trajectory';
GO
CREATE OR ALTER VIEW POINT_INTERACTIONS AS SELECT * FROM POINT_EVENTS WHERE kind='interaction';
GO
CREATE OR ALTER VIEW POINT_AI_INTERPRETATIONS AS SELECT * FROM POINT_EVENTS WHERE kind='ai_interpretation';
GO
CREATE OR ALTER VIEW POINT_EXPERIMENTS AS SELECT * FROM POINT_EVENTS WHERE kind='experiment';
GO
